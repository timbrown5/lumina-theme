export const createBase24Json = (colors: Base24Colors, themeName: string): string =>
  Base24.createBase24Json(colors, themeName);

export const createThemeDefinitionJson = (
  params: ThemeParams,
  accentOffsets: AccentOffsets | null,
  themeName: string,
  variant: string
): string => {
  const definition: Record<string, any> = {
    bgHue: params.bgHue,
    bgSat: params.bgSat,
    bgLight: params.bgLight,
    accentHue: params.accentHue,
    accentSat: params.accentSat,
    accentLight: params.accentLight,
    commentLight: params.commentLight,
    accentOffsets: accentOffsets ?? {
      red: { hue: 0 }, orange: { hue: 0 }, yellow: { hue: 0 }, green: { hue: 0 },
      cyan: { hue: 0 }, blue: { hue: 0 }, purple: { hue: 0 }, pink: { hue: 0 },
    },
  };

  if (params.colorOverrides && Object.keys(params.colorOverrides).length > 0) {
    definition.colorOverrides = params.colorOverrides;
  }

  const themeDefinition = { name: themeName, variant, definition };
  return JSON.stringify(themeDefinition, null, 2);
};

export const exportNeovimTheme = (
  params: ThemeParams,
  accentOffsets: AccentOffsets | null,
  themeName: string,
  variant: string
): string => {
  const colors = generateColors(params, accentOffsets);
  return createNvimTheme(colors, themeName, variant);
};

export const exportBase24Theme = (
  params: ThemeParams,
  accentOffsets: AccentOffsets | null,
  themeName: string
): string => {
  const colors = generateColors(params, accentOffsets);
  return createBase24Json(colors, themeName);
};

export const exportThemeDefinition = (
  params: ThemeParams,
  accentOffsets: AccentOffsets | null,
  themeName: string,
  variant: string
): string => {
  return createThemeDefinitionJson(params, accentOffsets, themeName, variant);
};

/**
 * Triggers a browser file download.
 */
export const triggerDownload = (filename: string, content: string, mimeType = 'application/json') => {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
};

/**
 * Saves theme JSON to the dev server filesystem.
 * Only works when running locally via Vite dev server.
 */
export const saveThemeToServer = async (filePath: string, content: string): Promise<boolean> => {
  try {
    const res = await fetch('/api/save-theme', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ path: filePath, content }),
    });
    return res.ok;
  } catch {
    return false;
  }
};
